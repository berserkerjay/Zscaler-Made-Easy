def one_line(v: Any) -> str:
    """Text for an HCL ``#`` comment: line breaks and other control
    characters become a space, so a name or reason from a pack or the
    tenant can never end the comment and start HCL of its own (a
    ``resource`` with a ``local-exec`` provisioner, say)."""
    return re.sub(r"[\s\x00-\x1f\x7f\u2028\u2029]+", " ", "" if v is None else str(v)).strip()


# The only interpolations an engine expression may carry: the references
# generate() itself writes for a dictionary (resource or data lookup).
_OWN_REF_RE = re.compile(r"\$\{(?!(?:data\.)?zia_dlp_dictionaries\.[a-z0-9_]+\.id\})")


def hcl_str(s: Any, *, interpolate: bool = False) -> str:
    """Quote a string for HCL, escaping backslashes, quotes and template
    sequences so regex patterns and literal ${ survive verbatim. With
    interpolate=True, ${...} references are left live (engine expressions)."""
    s = _LONE_SURROGATE.sub("\ufffd", "" if s is None else str(s))
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    # A bidirectional or invisible formatting character, and every other
    # control character (ESC, NUL, a line separator), is written as its
    # \uNNNN escape: the value Terraform reads is the same, but the file
    # never shows text in another order than it runs (CVE-2021-42574), and
    # `cat` or a diff of it never runs a terminal escape sequence.
    s = _ESCAPED.sub(_u_escape, s)
    if not interpolate:
        s = s.replace("${", "$${")
    s = s.replace("%{", "%%{")
    return f'"{s}"'


# A lone surrogate cannot be written as UTF-8 (nor held by an HCL string).
_LONE_SURROGATE = re.compile("[\ud800-\udfff]")
# Bidirectional marks, embeddings, overrides and isolates, and invisible format characters.
_INVISIBLE = re.compile("[\u061c\u200b-\u200f\u202a-\u202e\u2060-\u2064\u2066-\u2069\ufeff]")
# Control characters (C0 but tab, DEL, C1) and the Unicode line separators.
_CONTROL = re.compile("[\x00-\x08\x0a-\x1f\x7f-\x9f\u2028\u2029]")
_ESCAPED = re.compile(_INVISIBLE.pattern[:-1] + _CONTROL.pattern[1:-1] + "]")


def _u_escape(m: "re.Match") -> str:
    return "\\u%04x" % ord(m.group())
# Everything a reader (or the HCL scanner) could take as the end of a line.
_LINE_BREAKS = re.compile(r"\r\n|[\r\n\v\f\x1c-\x1e\x85\u2028\u2029]")


def hcl_comment(s: Any) -> str:
    """Text for a `#` comment: one line, whatever it carries. A name from
    the tenant or an uploaded pack with a line break in it would otherwise
    end the comment and put the rest of the name into the workspace as
    live HCL (a resource terraform apply would create)."""
    return _ESCAPED.sub("\ufffd", _LONE_SURROGATE.sub("\ufffd", _LINE_BREAKS.sub(" ", "" if s is None else str(s))))


def hcl_list(items: Iterable[Any], *, raw: bool = False) -> str:
    items = list(items)
    if not items:
        return "[]"
    body = ", ".join(str(i) if raw else hcl_str(i) for i in items)
    return f"[{body}]"


def slug(name: str, prefix: str = "") -> str:
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "x"
    if s[0].isdigit():
        s = "_" + s
    return f"{prefix}{s}"


class Slugger:
    """Unique, stable resource labels per resource type."""
    def __init__(self) -> None:
        self.used: Dict[str, Dict[str, str]] = {}
        self.labels: Dict[str, set] = {}   # per kind, the labels given out (a set: 10k rules stay linear)

    def get(self, kind: str, name: str) -> str:
        table = self.used.setdefault(kind, {})
        if name in table:
            return table[name]
        taken = self.labels.setdefault(kind, set())
        base = slug(name)
        cand, n = base, 2
        while cand in taken:
            cand, n = f"{base}_{n}", n + 1
        table[name] = cand
        taken.add(cand)
        return cand


def _attr(name: str, value: str, width: int = 28) -> str:
    return f"  {name.ljust(width)} = {value}\n"


_ATTR_LINE_RE = re.compile(r"^(\s*)([A-Za-z_][A-Za-z0-9_\-]*)\s*=\s*(.*\S)\s*$")


def _balanced(value: str) -> bool:
    """True when the attribute's value closes every bracket it opens on
    this line (strings and their escapes ignored), i.e. the attribute is a
    single line and takes part in `terraform fmt` alignment."""
    depth = 0
    quote = None
    i = 0
    while i < len(value):
        c = value[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = None
        elif c == '"':
            quote = '"'
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        i += 1
    return depth == 0 and quote is None


def hcl_fmt(text: str) -> str:
    """Lay the generated HCL out the way `terraform fmt` does, so a
    workspace is fmt-clean as written (the platform team's pre-commit hook
    and CI's `terraform fmt -check` pass without a second pass): within a
    run of consecutive single-line `key = value` attributes at one indent,
    the `=` signs line up on the longest key; a blank line, a comment, a
    nested block or a multi-line value ends the run and stands as written
    with single spaces around `=`. Trailing whitespace is dropped."""
    out: List[str] = []
    run: List[Tuple[str, str, str]] = []   # (indent, key, value)

    def flush() -> None:
        if not run:
            return
        width = max(len(k) for _, k, _ in run)
        for indent, key, value in run:
            out.append(f"{indent}{key.ljust(width)} = {value}")
        run.clear()

    for raw in text.split("\n"):
        line = raw.rstrip()
        m = _ATTR_LINE_RE.match(line)
        if m and _balanced(m.group(3)) and (not run or run[0][0] == m.group(1)):
            run.append((m.group(1), m.group(2), m.group(3)))
            continue
        flush()
        if m and _balanced(m.group(3)):
            run.append((m.group(1), m.group(2), m.group(3)))   # a new run at another indent
            continue
        if m:
            line = f"{m.group(1)}{m.group(2)} = {m.group(3)}"   # a multi-line value: single spaces, no alignment
        out.append(line)
    flush()
    return "\n".join(out)


