# Files an earlier version of this generator wrote under names it no longer
# uses, recognised by text only it put there, so a renamed file cannot leave
# a stale twin behind (two terraform blocks would fail validate).
_RETIRED = {"versions.tf": ('source  = "zscaler/zia"', "# Remote state (recommended for shared use)"),
            "provider.tf": ('provider "zia"', "# Credentials come from variables (see terraform.tfvars.example)")}


def _generated_here(path: str) -> bool:
    """True only for a file this generator wrote: a .tf starting with the
    provenance comment, or a retired file carrying its old markers. A
    user's own .tf, state, terraform.tfvars and the lock file never are."""
    name = os.path.basename(path)
    if not os.path.isfile(path) or os.path.islink(path):
        return False
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read(4096)
    except (OSError, UnicodeDecodeError):
        return False
    if name in _RETIRED:
        return all(m in text for m in _RETIRED[name])
    return name.endswith(".tf") and text.startswith(GENERATED_MARK)


def _no_follow_opener(path: str, flags: int) -> int:
    return safe_files._opener(path, flags | getattr(os, "O_NOFOLLOW", 0))


def write_workspace(files: Dict[str, str], out_dir: str) -> List[str]:
    """Write the workspace, and remove the files this generator wrote
    earlier that it no longer emits (see _generated_here). Anything else in
    the folder (the team's own .tf files, terraform.tfvars, state,
    .terraform/, the lock file) is left alone."""
    safe_files.private_makedirs(out_dir)
    written = []
    for name, content in files.items():
        path = os.path.join(out_dir, name)
        if os.path.islink(path):
            os.remove(path)   # a link planted in the folder is replaced, never written through
        # Owner-only (the pack's policy), and never through a link (O_NOFOLLOW: one planted after the check fails the write).
        with open(path, "w", encoding="utf-8", newline="\n", opener=_no_follow_opener) as f:
            f.write(content)
        written.append(path)
    for name in os.listdir(out_dir):
        if name not in files and _generated_here(os.path.join(out_dir, name)):
            os.remove(os.path.join(out_dir, name))
    return written


def remove_generated(out_dir: str, names: Iterable[str] = ()) -> List[str]:
    """Remove the files this generator wrote in `out_dir` (and, of `names`,
    those carrying a Zscaler Made Easy marker), leaving state, terraform.tfvars,
    .terraform/, the lock file and anything else untouched. Used when a
    compile is blocked, so no deployable configuration is left behind."""
    removed = []
    if not os.path.isdir(out_dir):
        return removed
    for name in os.listdir(out_dir):
        path = os.path.join(out_dir, name)
        marked = False
        if name in names and os.path.isfile(path) and not os.path.islink(path):
            try:
                with open(path, encoding="utf-8") as f:
                    head = f.read(4096)
                    marked = "Zscaler Made Easy" in head or "DLP-Check" in head   # older workspaces say DLP-Check
            except (OSError, UnicodeDecodeError):
                marked = False
        if _generated_here(path) or marked:
            os.remove(path)
            removed.append(name)
    return removed



def zip_workspaces(workspaces: Dict[str, Dict[str, str]]) -> bytes:
    """{pack_id: files} -> zip bytes with one folder per pack."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for pack_id, files in workspaces.items():
            for name, content in files.items():
                z.writestr(f"{pack_id}/{name}", content)
    return buf.getvalue()


def split_report(report: Dict[str, Any], pack_id: str) -> Dict[str, Any]:
    """Restrict a multi-pack preflight report to the items of one pack."""
    items = [i for i in report.get("items", []) if pack_id in (i.get("packs") or [])]
    return dict(report, items=items)


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Small CLI for local use and for regenerating terraform/<pack>/. With
    --assessor the descriptions name that person; without it they take the
    required `assessor` variable, so nothing is applied untagged (rule 2)."""
    import argparse
    import sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from dlp_importer import discover_packs

    ap = argparse.ArgumentParser(description="Generate Terraform workspaces for DLP packs.")
    ap.add_argument("packs", nargs="*", help="pack ids (default: all)")
    ap.add_argument("--out", default="terraform", help="output root (one folder per pack)")
    ap.add_argument("--assessor", default="",
                    help="the assessor's name every description carries; without it the workspace "
                         "requires the `assessor` variable at plan/apply time (never Zscaler Made Easy)")
    args = ap.parse_args(argv)
    assessor = " ".join(str(args.assessor or "").split())
    if args.assessor and not assessor:
        sys.exit("--assessor is blank: name the assessor, or leave the option out to require it at apply time")
    import pack_deploy
    if pack_deploy.is_tool_name(assessor):
        sys.exit("--assessor must name the person who assesses and deploys the pack, not the tool")
    known = {p["id"]: p for p in discover_packs()}
    ids = args.packs or sorted(known)
    for pid in ids:
        if pid not in known:
            sys.exit(f"unknown pack: {pid}")
        files = generate({"id": pid, "dir": known[pid]["dir"]}, assessor=assessor)
        write_workspace(files, os.path.join(args.out, pid))
        print(f"{pid}: {len(files)} files -> {os.path.join(args.out, pid)}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
