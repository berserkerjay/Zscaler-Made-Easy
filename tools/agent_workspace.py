"""Compile and check the agent workspace (agent-workspace/).

The workspace follows a layered-context layout: IDENTITY.md (where am I),
CONTEXT.md (where do I go), stages/*/CONTEXT.md (what do I do: Inputs,
Process, Outputs), _config/ (rules, with an _index.md) and references/
(facts about the code, with an _index.md). Two reference files are compiled
from the source tree so they can't drift from it:

  references/architecture.md  every top-level Python module, static page
                              script and page, with the first line of its
                              docstring or header comment
  references/assumed.md       every "assumed" marker in the source: Zscaler
                              behaviour the code relies on but could not
                              verify against the SDK or Zscaler's docs

  python tools/agent_workspace.py          rewrite the compiled files
  python tools/agent_workspace.py --check  fail if anything is stale or the
                                           workspace breaks its own rules
"""
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WS = os.path.join(ROOT, "agent-workspace")

# Rough token budgets per layer (4 characters ≈ 1 token), from the method.
BUDGETS = {"IDENTITY.md": 1200, "CONTEXT.md": 450}
STAGE_BUDGET = 750
CONFIG_BUDGET = 2000
STAGE_SECTIONS = ("## Inputs", "## Process", "## Outputs", "## Review gate")
ASSUMED = re.compile(r"#\s*assumed\b|\bASSUMED\b|//\s*assumed\b", re.I)
SKIP_DIRS = {"tests", "docs", "tools", "static", "browser_extension", "terraform", "node_modules", ".git", ".venv",
             "agent-workspace", "skills", ".agents", "fed_policy_pack", "irs_fti_pack"}


def _tokens(text):
    return len(text) // 4


def _first_doc_line(path):
    try:
        with open(path, encoding="utf-8") as f:
            src = f.read()
    except (OSError, UnicodeDecodeError):
        return ""
    if path.endswith(".py"):
        try:
            doc = ast.get_docstring(ast.parse(src)) or ""
        except SyntaxError:
            doc = ""
        line = doc.strip().splitlines()[0] if doc.strip() else ""
    else:
        m = re.search(r"/\*\s*(.+?)\s*(?:\*/|$)|//\s*(.+)|<title>(.+?)</title>", src[:4000], re.S)
        line = next((g for g in (m.groups() if m else ()) if g), "")
        line = line.strip().splitlines()[0] if line.strip() else ""
    line = re.sub(r"[─━═]+", "", line).strip(" -—:")
    return (line[:157] + "…") if len(line) > 158 else line


def _modules():
    py = sorted(f for f in os.listdir(ROOT) if f.endswith(".py") and os.path.isfile(os.path.join(ROOT, f)))
    st = os.path.join(ROOT, "static")
    js = sorted(f for f in os.listdir(st) if f.endswith(".js")) if os.path.isdir(st) else []
    html = sorted(f for f in os.listdir(st) if f.endswith(".html")) if os.path.isdir(st) else []
    return py, js, html


def compile_architecture():
    py, js, html = _modules()
    out = ["# Architecture map (compiled — do not edit by hand)", "",
           "Generated by `python tools/agent_workspace.py`. One line per file: what it is, from its own docstring or header.",
           "Find the files a change touches here, then read only those.", ""]
    for title, folder, names in (("Python modules (repository root)", "", py), ("Page scripts (static/)", "static/", js),
                                 ("Pages (static/)", "static/", html)):
        out += [f"## {title}", "", "| File | What it is |", "|---|---|"]
        for n in names:
            desc = _first_doc_line(os.path.join(ROOT, folder, n)).replace("|", "\\|") or "—"
            out.append(f"| `{folder}{n}` | {desc} |")
        out.append("")
    return "\n".join(out)


def compile_assumed():
    rows = []
    for base, dirs, files in os.walk(ROOT):
        rel = os.path.relpath(base, ROOT)
        top = rel.split(os.sep)[0]
        if top in SKIP_DIRS and top != "static" or any(p.startswith(".") and p not in (".",) for p in rel.split(os.sep)):
            dirs[:] = []
            continue
        if top == "static":
            files = [f for f in files if f.endswith(".js")]
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS - {"static"} and not d.startswith(".")]
        for f in sorted(files):
            if not f.endswith((".py", ".js")):
                continue
            path = os.path.join(base, f)
            try:
                with open(path, encoding="utf-8") as fh:
                    lines = fh.read().splitlines()
            except (OSError, UnicodeDecodeError):
                continue
            for i, line in enumerate(lines, 1):
                if ASSUMED.search(line):
                    text = line.strip().lstrip("#/ ").strip()
                    text = (text[:137] + "…") if len(text) > 138 else text
                    rows.append((os.path.relpath(path, ROOT).replace(os.sep, "/"), i, text.replace("|", "\\|")))
    rows.sort()
    out = ["# Assumed Zscaler behaviour (compiled — do not edit by hand)", "",
           "Every place the code relies on Zscaler behaviour it could not verify against the installed SDK or Zscaler's",
           "documentation. A verify stage treats these as unproven; a spec that depends on one says so.", "",
           f"{len(rows)} markers.", "", "| File:line | Note |", "|---|---|"]
    out += [f"| `{p}:{n}` | {t} |" for p, n, t in rows]
    return "\n".join(out) + "\n"


COMPILED = {"references/architecture.md": compile_architecture, "references/assumed.md": compile_assumed}


def problems():
    """Every way the workspace breaks its own rules (empty when it's fine)."""
    bad = []
    for rel, fn in COMPILED.items():
        path = os.path.join(WS, rel)
        want = fn()
        have = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if have != want:
            bad.append(f"{rel} is stale: run python tools/agent_workspace.py")
    for name, budget in BUDGETS.items():
        text = open(os.path.join(WS, name), encoding="utf-8").read()
        if _tokens(text) > budget:
            bad.append(f"{name} is over its budget ({_tokens(text)} > {budget} tokens)")
    stages = os.path.join(WS, "stages")
    for s in sorted(os.listdir(stages)):
        path = os.path.join(stages, s, "CONTEXT.md")
        if not os.path.exists(path):
            bad.append(f"stages/{s} has no CONTEXT.md")
            continue
        text = open(path, encoding="utf-8").read()
        bad += [f"stages/{s}/CONTEXT.md lacks '{sec}'" for sec in STAGE_SECTIONS if sec not in text]
        if _tokens(text) > STAGE_BUDGET:
            bad.append(f"stages/{s}/CONTEXT.md is over its budget ({_tokens(text)} tokens)")
        if f"stages/{s}/" not in open(os.path.join(WS, "CONTEXT.md"), encoding="utf-8").read():
            bad.append(f"CONTEXT.md does not route to stages/{s}/")
    for layer in ("_config", "references"):
        folder = os.path.join(WS, layer)
        index = open(os.path.join(folder, "_index.md"), encoding="utf-8").read()
        for f in sorted(os.listdir(folder)):
            if f == "_index.md" or not f.endswith(".md"):
                continue
            if f not in index:
                bad.append(f"{layer}/_index.md does not list {f}")
            if layer == "_config" and _tokens(open(os.path.join(folder, f), encoding="utf-8").read()) > CONFIG_BUDGET:
                bad.append(f"_config/{f} is over its budget")
        for listed in re.findall(r"^\| ([\w.-]+\.md) \|", index, re.M):
            if not os.path.exists(os.path.join(folder, listed)):
                bad.append(f"{layer}/_index.md lists {listed}, which does not exist")
    # Every file a stage or config page points at must exist.
    for base, _dirs, files in os.walk(WS):
        if os.path.basename(base) == "output":
            continue
        for f in files:
            if not f.endswith(".md"):
                continue
            text = open(os.path.join(base, f), encoding="utf-8").read()
            for ref in re.findall(r"`((?:_config|references|stages)/[\w./-]+\.md)`", text):
                if not os.path.exists(os.path.join(WS, ref)):
                    bad.append(f"{os.path.relpath(os.path.join(base, f), WS)} points at missing {ref}")
    return bad


def main(argv):
    if "--check" in argv:
        bad = problems()
        for b in bad:
            print("agent workspace:", b)
        return 1 if bad else 0
    for rel, fn in COMPILED.items():
        with open(os.path.join(WS, rel), "w", encoding="utf-8", newline="\n") as f:
            f.write(fn())
    print("agent workspace: compiled", ", ".join(COMPILED))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
